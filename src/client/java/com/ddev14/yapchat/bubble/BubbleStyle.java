package com.ddev14.yapchat.bubble;

/** Look of the chat bubbles above players. */
public enum BubbleStyle {
	/** Translucent dark box with a small tail (the original look). */
	DARK,
	/** White pixel-art comic bubble with a dark outline. */
	WHITE,
	/** Like vanilla item tooltips: dark purple with a violet frame. */
	TOOLTIP,
	/** Like vanilla name tags: plain translucent strip, no tail. */
	NAMETAG
}
